android {
    namespace = "dev.azwall.app"
    compileSdk = 37

    defaultConfig {
        applicationId = "dev.azwall"
        minSdk = 30
        targetSdk = 37
        versionName = "0.8.0"
        // Stores refuse a build number they saw: it follows the version (0.8.0 → 800), as on iOS.
        versionCode = versionName!!.split(".").map(String::toInt).let { (major, minor, patch) -> major * 10_000 + minor * 100 + patch }
        ndk { abiFilters += listOf("arm64-v8a", "x86_64") }
    }

    // The Play upload key, from android/keystore.properties (never committed; see docs/release.md). Without it the
    // release is built unsigned.
    val upload = rootProject.file("keystore.properties").takeIf { it.exists() }?.let { file ->
        Properties().apply { file.inputStream().use { load(it) } }
    }
    signingConfigs {
        if (upload != null) create("upload") {
            storeFile = rootProject.file(upload.getProperty("storeFile"))
            storePassword = upload.getProperty("storePassword")
            keyAlias = upload.getProperty("keyAlias")
            keyPassword = upload.getProperty("keyPassword")
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"))
            signingConfig = signingConfigs.findByName("upload")
        }
        // The release as R8 makes it, signed with the debug key and installed beside the app: what is shipped can
        // be tried on a phone without replacing the wallet installed there.
        create("staging") {
            initWith(getByName("release"))
            signingConfig = signingConfigs.getByName("debug")
            applicationIdSuffix = ".staging"
            versionNameSuffix = "-staging"
            matchingFallbacks += "release"
        }
    }

    // The CRS is read with openFd to compare sizes, and is already incompressible.
    androidResources { noCompress += "dat" }
    // Barretenberg libraries are opened by path (dlopen), so they must be extracted on install.
    packaging { jniLibs { useLegacyPackaging = true } }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    buildFeatures {
        compose = true
        buildConfig = true
    }
}

val repoRoot = rootDir.parentFile

// assets/ is generated by the task below and scripts/fetch-crs.sh, and shared with the iOS app. icons/ holds the
// start page's dApp icons (icons/dapps/<host>.png), shipped so that showing them asks nothing of those sites.
androidComponents {
    onVariants { variant ->
        variant.sources.assets?.addStaticSourceDirectory(repoRoot.resolve("assets").path)
        variant.sources.assets?.addStaticSourceDirectory(repoRoot.resolve("icons").path)
    }
}

// networks.json + .env → assets/azwall-config.json (RPC endpoints per network).
val generateAzwallConfig by tasks.registering(Exec::class) {
    workingDir = repoRoot
    commandLine("cargo", "run", "--quiet", "-p", "azwall-core", "--bin", "azwall-config", "--", "--out", "assets/azwall-config.json")
    inputs.file(repoRoot.resolve("networks.json"))
    inputs.files(repoRoot.resolve(".env")).optional()
    outputs.file(repoRoot.resolve("assets/azwall-config.json"))
}

// pxe/<bundle> → assets/pxe/<bundle>/ (one PXE host per Aztec version, see networks.json).
val buildPxeHosts by tasks.registering(Exec::class) {
    workingDir = repoRoot.resolve("pxe")
    commandLine("sh", "-c", "pnpm install --frozen-lockfile --silent && pnpm build")
    inputs.files(fileTree(repoRoot.resolve("pxe")) { include("*/src/**", "*/package.json", "*/vite.config.ts", "pnpm-lock.yaml") })
    outputs.dir(repoRoot.resolve("assets/pxe"))
}

tasks.named("preBuild") { dependsOn(generateAzwallConfig, buildPxeHosts) }

// What reaches a store must be built for it: the Rust core in release mode for every architecture shipped, and only
// the registry's public endpoints (an RPC URL from .env may carry its owner's API key, readable by anyone in the APK).
@Suppress("UNCHECKED_CAST")
val checkReleaseInputs by tasks.registering {
    dependsOn(generateAzwallConfig)
    doLast {
        val staged = repoRoot.resolve("build/android-natives").takeIf { it.exists() }?.readText()?.trim()?.split(" ").orEmpty()
        // Phones: Barretenberg is built for arm64 only (x86_64 is for emulators, in debug builds).
        val abis = listOf("arm64-v8a")
        if (staged.firstOrNull() != "release" || !staged.drop(1).containsAll(abis)) {
            throw GradleException("the Rust core staged is not a release build for ${abis.joinToString()}: run scripts/build-android.sh --release ${abis.joinToString(" ")}")
        }
        val json = groovy.json.JsonSlurper()
        val networks = { file: File -> (json.parse(file) as Map<String, Any?>)["networks"] as List<Map<String, Any?>> }
        val public = networks(repoRoot.resolve("networks.json")).flatMap { n ->
            val l1 = n["l1"] as Map<String, Any?>?
            listOfNotNull(n["defaultRpc"], l1?.get("rpc"), l1?.get("fallbackRpc")).map { it.toString() }
        }.toSet()
        val shipped = networks(repoRoot.resolve("assets/azwall-config.json")).flatMap { n ->
            listOfNotNull(n["rpcUrl"]?.toString()) + (n["l1RpcUrls"] as List<Any?>?).orEmpty().map { it.toString() }
        }
        val private = shipped.filter { it !in public }
        if (private.isNotEmpty()) {
            val hosts = private.map { URI(it).host }.distinct().joinToString()
            throw GradleException("assets/azwall-config.json holds endpoints from .env ($hosts): a release ships the registry's public ones only; clear them in .env and build again")
        }
    }
}
afterEvaluate {
    listOf("preReleaseBuild", "preStagingBuild").forEach { name -> tasks.findByName(name)?.dependsOn(checkReleaseInputs) }
}


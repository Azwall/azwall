val repoRoot = rootDir.parentFile

// assets/ is generated by the task below and scripts/fetch-crs.sh, and shared with the iOS app. icons/ holds the
// start page's dApp icons (icons/dapps/<host>.png), shipped so that showing them asks nothing of those sites.
androidComponents {
    onVariants { variant ->
        variant.sources.assets?.addStaticSourceDirectory(repoRoot.resolve("assets").path)
        variant.sources.assets?.addStaticSourceDirectory(repoRoot.resolve("icons").path)
    }
}

// networks.json + .env → assets/azwall-config.json (RPC endpoints per network).
val generateAzwallConfig by tasks.registering(Exec::class) {
    workingDir = repoRoot
    commandLine("cargo", "run", "--quiet", "-p", "azwall-core", "--bin", "azwall-config", "--", "--out", "assets/azwall-config.json")
    inputs.file(repoRoot.resolve("networks.json"))
    inputs.files(repoRoot.resolve(".env")).optional()
    outputs.file(repoRoot.resolve("assets/azwall-config.json"))
}

// pxe/<bundle> → assets/pxe/<bundle>/ (one PXE host per Aztec version, see networks.json).
val buildPxeHosts by tasks.registering(Exec::class) {
    workingDir = repoRoot.resolve("pxe")
    commandLine("sh", "-c", "pnpm install --frozen-lockfile --silent && pnpm build")
    inputs.files(fileTree(repoRoot.resolve("pxe")) { include("*/src/**", "*/package.json", "*/vite.config.ts", "pnpm-lock.yaml") })
    outputs.dir(repoRoot.resolve("assets/pxe"))
}

tasks.named("preBuild") { dependsOn(generateAzwallConfig, buildPxeHosts) }

